package com.jrb.models

import kotlinx.serialization.Serializable

// ==========================================
// DTOs - What we send to the app
// ==========================================

@Serializable
data class ExpenseDto(
    val id: String,
    val groupId: String,
    val paidById: String,
    val description: String,
    val amount: Double,
    val category: String,
    val receiptUrl: String? = null,
    val createdAt: Long,
    val updatedAt: Long,
    val deletedAt: Long? = null,
    // We send the splits nested inside the expense so the app doesn't have to fetch them separately
    val splits: List<ExpenseSplitDto> = emptyList()
)

@Serializable
data class ExpenseSplitDto(
    val id: String,
    val expenseId: String,
    val owedById: String,
    val amount: Double,
    val percentage: Double,
    val updatedAt: Long,
    val deletedAt: Long? = null
)

// ==========================================
// REQUESTS - What the mobile app sends to server
// ==========================================

@Serializable
data class CreateExpenseRequest(
    val id: String, // UUID generated by the mobile app
    val groupId: String,
    val paidById: String,
    val description: String,
    val amount: Double,
    val category: String,
    val receiptUrl: String? = null,
    val createdAt: Long,
    // A single expense MUST come with how it's divided
    val splits: List<CreateExpenseSplitRequest>
)

@Serializable
data class CreateExpenseSplitRequest(
    val id: String, // UUID generated by the mobile app
    val owedById: String,
    val amount: Double,
    val percentage: Double
)

@Serializable
data class UpdateExpenseRequest(
    val description: String,
    val amount: Double,
    val category: String,
    val receiptUrl: String? = null,
    val splits: List<CreateExpenseSplitRequest>
)