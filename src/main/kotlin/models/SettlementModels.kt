package com.jrb.models

import kotlinx.serialization.Serializable

// ==========================================
// DTOs - What we send to the app
// ==========================================

@Serializable
data class SettlementDto(
    val id: String,
    val groupId: String,
    val payerId: String,
    val receiverId: String,
    val amount: Double,
    val method: String, // e.g., "CASH", "BIZUM", "WAIVED"
    val createdAt: Long,
    val updatedAt: Long,
    val deletedAt: Long? = null
)

// ==========================================
// REQUESTS - What the mobile app sends to us
// ==========================================

@Serializable
data class CreateSettlementRequest(
    val id: String, // UUID generated by the mobile app
    val groupId: String,
    val payerId: String,
    val receiverId: String,
    val amount: Double,
    val method: String,
    val createdAt: Long
)

@Serializable
data class UpdateSettlementRequest(
    val amount: Double,
    val method: String
)